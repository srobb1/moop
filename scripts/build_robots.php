<?php
/**
 * robots.txt for one host, from the repo's robots.txt (the single source of the rules).
 *
 *   php scripts/build_robots.php <site folder> [<site folder> ...] > robots.txt
 *   e.g. php scripts/build_robots.php /var/www/html/cuttingclass            (cuttingclass.stowers.org)
 *        php scripts/build_robots.php /var/www/html/moop /var/www/html/cuttingclass   (one host, two sites)
 *
 * robots.txt belongs to a HOST NAME, not to a site: crawlers only ever ask for /robots.txt at the
 * root. The repo copy is written for "/moop/". Every line naming "/moop/" is repeated once per site
 * with that site's link prefix ("/moop", "/cuttingclass", or "" for a site served at its domain's
 * root -- the link_prefix setting, see includes/config_init.php). Everything else is copied as is.
 *
 * The prefix is read from each site's config/config_editable.json ('link_prefix'), else "/" + the
 * folder name -- the same default as config/site_config.php. Prints to stdout; root installs it
 * where nginx serves /robots.txt for that host (notes/MOVE_SITE_TO_OWN_ADDRESS.md).
 */
if (PHP_SAPI !== 'cli') { http_response_code(403); exit("CLI only\n"); }
$sites = array_slice($argv, 1);
if (!$sites) { fwrite(STDERR, "usage: php build_robots.php <site folder> [...]\n"); exit(2); }

$prefixes = [];
foreach ($sites as $dir) {
    $dir = rtrim($dir, '/');
    if (!is_dir($dir)) { fwrite(STDERR, "not a folder: $dir\n"); exit(1); }
    $cfg = json_decode((string) @file_get_contents("$dir/config/config_editable.json"), true);
    $p = trim((string) ($cfg['link_prefix'] ?? ''));
    if ($p === '') $p = '/' . basename($dir);
    $p = $p === '/' ? '' : '/' . trim($p, '/');
    if ($p !== '' && !preg_match('#^(/[A-Za-z0-9._~-]+)+$#', $p)) { fwrite(STDERR, "unusable link_prefix in $dir: $p\n"); exit(1); }
    $prefixes[] = $p;
}

$template = file(__DIR__ . '/../robots.txt', FILE_IGNORE_NEW_LINES);
$out = ["# Generated by scripts/build_robots.php from the repo's robots.txt for: " . implode(', ', $sites)];
foreach ($template as $line) {
    if (strpos($line, '/moop/') === false) { $out[] = $line; continue; }
    foreach ($prefixes as $p) $out[] = str_replace('/moop/', $p . '/', $line);
}
echo implode("\n", $out), "\n";
